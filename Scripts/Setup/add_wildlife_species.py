"""Wildlife on every island (November 6): build the new species and add every island's missing animals, in one editor run
and without a world rebuild (owner, November 6). Safe to run again. Run in the editor, outside Play:
    UnrealEditor.exe EW.uproject -SCCProvider=None -ExecCmds="py <this file>"

1. Builds the models, material instances and definitions of the newest species only: build_animals.MORE_SPECIES (November 7,
   the rest of the island plan), or NEW_SPECIES (November 6) with EW_SPECIES=NEW. The other animals keep their models,
   some of which were generated by Scenario.
2. Runs place_animals.py, which adds only what each island's plan (wildlife_distribution.py) is missing and leaves every
   animal already in the world where it is.
Writes Saved/AddWildlifeSpeciesResult.json beside place_animals' own AnimalsExpansionResult.json.
"""
import json
import runpy
import sys
import time
from pathlib import Path
import unreal

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build_animals as B  # noqa: E402


def main():
    assert not unreal.EWEditorVerificationLibrary.get_play_worlds(), 'Stop Play first'
    meat = unreal.load_asset(B.RAW_MEAT)
    assert meat, 'Raw Meat is missing (build_fish.py makes it)'
    chosen = __import__('os').environ.get('EW_SPECIES', '')
    # EW_SPECIES=NEW for the November 6 seven, or a comma-separated list of species to rebuild (e.g. Turtle).
    species = B.NEW_SPECIES if chosen == 'NEW' else tuple(chosen.split(',')) if chosen else B.MORE_SPECIES
    defs = B.build_definitions(meat, only=species)
    assert set(defs) == set(species), sorted(defs)
    runpy.run_path(str(HERE / 'place_animals.py'), run_name='__main__')
    placed = json.loads(Path(unreal.Paths.project_saved_dir(), 'AnimalsExpansionResult.json').read_text())
    Path(unreal.Paths.project_saved_dir(), 'AddWildlifeSpeciesResult.json').write_text(json.dumps({
        'success': True, 'species_built': sorted(defs), 'new_animals': placed['new_animals'], 'by_kind': placed['by_kind'],
        'finished_utc': time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())}, indent=2))
    unreal.log(f'EWWILDLIFE done: {placed["new_animals"]} animals added {placed["by_kind"]}')


if __name__ == '__main__':
    try:
        main()
    finally:
        if __import__('os').environ.get('EW_QUIT_WHEN_DONE') == '1':
            unreal.SystemLibrary.quit_editor()
