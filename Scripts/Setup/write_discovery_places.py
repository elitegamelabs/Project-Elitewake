"""Writes Source/EW/World/EWPlacesTable.inl: every named place a survivor can discover (FUTURE_IMPLEMENTATIONS Part 8, 63,
the Captain's discovery journal), from the world's own data so nothing is copied by hand.

  islands     world_layout.ISLANDS (ellipse: centre, radii, turn) named from world_islands.ISLANDS
  Freeports   world_layout.PORTS, one per region's village island (CLAUDE.md 5.7)
  reefs       world_reefs.REEFS, named by their compass bearing from the middle of the world
  caves       world_terrain.CAVES, each island's one cave (sea caverns on Plains3, Desert3 and Jungle3)

Plain Python, no Unreal: run it after any of those change, then rebuild. Scripts/Tests/test_discovery_places.py fails when
the checked-in table no longer matches.
    python Scripts/Setup/write_discovery_places.py
"""
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import world_islands as WI  # noqa: E402
import world_layout as L  # noqa: E402
import world_reefs as R  # noqa: E402
import world_terrain as T  # noqa: E402

OUT = os.path.normpath(os.path.join(HERE, '..', '..', 'Source', 'EW', 'World', 'EWPlacesTable.inl'))

ISLAND_REACH = 15000.0     # cm past an island's shore ellipse: sighted from a ship close in, or ashore
FREEPORT_RADIUS = 12000.0  # cm from a Port's site: inside its harbour and town
REEF_RADIUS = 6000.0       # cm: over the reef (corals lie within 32 m of its centre)
SEA_CAVE_RADIUS = 3500.0   # cm from the pool's middle (the pool is 44 x 58 m)
LAND_CAVE_RADIUS = 1200.0  # cm from the chamber's middle
CAVE_HEIGHT = {'sea': 2500.0, 'inland': 700.0, 'coastal': 700.0}  # cm above or below the chamber: not from the hill over it

# Compass words for a bearing; north is +Y and east is -X (Source/EW/World/EWNorth.h).
COMPASS = ('North', 'Northeast', 'East', 'Southeast', 'South', 'Southwest', 'West', 'Northwest')


def island_name(key):
    name = WI.ISLANDS[key]['name'].split(' ', 1)[1]
    return 'Starter Isle' if name == 'Starter' else name


def bearing(x, y):
    angle = math.degrees(math.atan2(-x, y)) % 360.0   # clockwise from north, east at 90
    return COMPASS[int((angle + 22.5) // 45) % 8]


def places():
    """[(id, name, kind, region, x, y, rx, ry, turn, z, z_range, note)] in a fixed order."""
    out = []
    for i in L.ISLANDS:
        info = WI.ISLANDS[i.key]
        note = 'Known for ' + ', '.join(info['specialty']) + '.'
        out.append((i.key, island_name(i.key), 'Island', i.region, i.cx, i.cy, i.rx + ISLAND_REACH, i.ry + ISLAND_REACH,
                    i.turn, 0.0, 0.0, note))
    for region in WI.REGIONS:
        port = L.PORTS[region]
        key = WI.VILLAGES[region]
        name = 'Saltreach Freeport' if region == 'Plains' else island_name(key) + ' Freeport'
        out.append(('Freeport_' + region, name, 'Freeport', region, port.cx, port.cy, FREEPORT_RADIUS, FREEPORT_RADIUS, 0.0,
                    0.0, 0.0, 'The ' + region + ' village: merchants, a harbour and safe ground.'))
    for reef in R.REEFS:
        out.append((reef.key, bearing(reef.cx, reef.cy) + ' Reef', 'Reef', 'OpenSea', reef.cx, reef.cy, REEF_RADIUS,
                    REEF_RADIUS, 0.0, 0.0, 0.0, 'Glowing corals on a seamount in the open ocean.'))
    for key, cave in T.CAVES.items():
        x, y = cave.world(cave.chamber_u, 0.0)
        sea = cave.kind == 'sea'
        radius = SEA_CAVE_RADIUS if sea else LAND_CAVE_RADIUS
        out.append(('Cave_' + key, island_name(key) + (' Sea Cavern' if sea else ' Cave'), 'Cave', cave.island.region, x, y,
                    radius, radius, 0.0, cave.floor + cave.chamber_z, CAVE_HEIGHT[cave.kind],
                    'A hidden berth a ship can enter from the sea.' if sea else 'A sheltered cave.'))
    return out


def text():
    lines = ['// Generated by Scripts/Setup/write_discovery_places.py from the world data; do not edit by hand.',
             '// {Id, Name, Kind, Region, Centre, Radii, Turn, Z, ZRange, Note}  (cm, radians; ZRange 0: any height)']
    for pid, name, kind, region, x, y, rx, ry, turn, z, zr, note in places():
        lines.append('{TEXT("%s"), TEXT("%s"), EEWPlaceKind::%s, EEWRegion::%s, FVector2D(%.0f.f, %.0f.f), FVector2D(%.0f.f, %.0f.f), '
                     '%.4ff, %.0f.f, %.0f.f, TEXT("%s")},' % (pid, name, kind, region, x, y, rx, ry, turn, z, zr, note))
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text())
    print('wrote', OUT, len(places()), 'places')
